def points(path):
    return [(float(x), float(y)) for x, y in re.findall(r"[ML](-?[\d.]+) (-?[\d.]+)", path)]


def reach():
    """vibb-icon.py's reach: the rings' largest coordinate plus half a stroke, in path units (the
    launcher scales it to 90 dp, so the mark at rest is 2 x 0.94 x 90 = 169 dp across)."""
    return max(abs(v) for p in RINGS for xy in points(p) for v in xy) + STROKE / 2


def load_screens():
    data = json.load(open(SCREENS, encoding="utf-8"))
    return data["mark_share"], data["version"], data["screens"]


def pixels(screen):
    return screen["width"] * screen["ratio"], screen["height"] * screen["ratio"]


def file_name(screen):
    w, h = pixels(screen)
    return f"startup-{w}x{h}.png"


def mark(diameter):
    """The mark on the night ground, `diameter` px across (the outer ring's outer edges)."""
    side = diameter + 4
    big = side * SUPERSAMPLE
    unit = diameter * SUPERSAMPLE / (2 * RING_REST * reach())
    centre = big / 2
    rings = Image.new("L", (big, big), 0)
    draw = ImageDraw.Draw(rings)
    # Each ring as its stroke's outline - the polyline moved half a stroke out and in along each
    # point's normal - filled, then its inside cleared (a wide line leaves seams at its joints).
    # Outer ring first, so clearing an inside never touches a ring drawn already.
    half = STROKE / 2
    for path in RINGS:
        pts = points(path)
        outer, inner = [], []
        for i, (x, y) in enumerate(pts):
            (ax, ay), (bx, by) = pts[i - 1], pts[(i + 1) % len(pts)]
            nx, ny = by - ay, ax - bx
            length = (nx * nx + ny * ny) ** 0.5
            nx, ny = nx / length, ny / length
            if nx * x + ny * y < 0:
                nx, ny = -nx, -ny
            for edge, sign in ((outer, 1), (inner, -1)):
                edge.append((
                    centre + (x + sign * half * nx) * RING_REST * unit,
                    centre + (y + sign * half * ny) * RING_REST * unit,
                ))
        draw.polygon(outer, fill=255)
        draw.polygon(inner, fill=0)
    core = Image.new("L", (big, big), 0)
    r = CORE_R * CORE_REST * unit
    ImageDraw.Draw(core).ellipse((centre - r, centre - r, centre + r, centre + r), fill=255)
    rings = rings.reduce(SUPERSAMPLE).point(lambda v: round(v * RING_ALPHA))
    core = core.reduce(SUPERSAMPLE)
    tile = Image.new("RGB", (side, side), NIGHT)
    tile.paste(Image.new("RGB", (side, side), RING), (0, 0), rings)
    tile.paste(Image.new("RGB", (side, side), CORE), (0, 0), core)
    return tile


def render(screen, share):
    w, h = pixels(screen)
    diameter = round(share * min(w, h))
    image = Image.new("RGB", (w, h), NIGHT)
    tile = mark(diameter)
    image.paste(tile, ((w - tile.width) // 2, (h - tile.height) // 2))
    # Few colours: the ground, the rings' and the core's edges.
    return image.quantize(colors=64, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)


def link(screen, version):
    return (
        '<link rel="apple-touch-startup-image" media="(device-width: {w}px) and (device-height: {h}px) '
        'and (-webkit-device-pixel-ratio: {r}) and (orientation: portrait)" href="/static/startup/{f}?v={v}">'
    ).format(w=screen["width"], h=screen["height"], r=screen["ratio"], f=file_name(screen), v=version)


def head_block(screens, version):
    return "\n".join([BEGIN] + [link(s, version) for s in screens] + [END])


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    assert head[:8] == b"\x89PNG\r\n\x1a\n", path
    return struct.unpack(">II", head[16:24])


def current_block(head):
    start, end = head.find(BEGIN), head.find(END)
    assert 0 <= start < end, "head.html has no start-up images block"
    return head[start:end + len(END)]


def selftest():
    share, version, screens = load_screens()
    names = [file_name(s) for s in screens]
    assert len(set(names)) == len(names), "two screens with one size"
    assert 0.2 < share < 0.6
    assert len(RINGS) == 4 and all(len(points(p)) > 100 for p in RINGS)
    # The launcher's numbers: splash_vibb_breathe.xml's group scale is vibb-icon.py's 90 / reach.
    assert f"{90 / reach():.4f}" == "3.3645", reach()
    head = open(HEAD, encoding="utf-8").read()
    assert current_block(head) == head_block(screens, version), "head.html's links differ: run the script"
    for screen, name in zip(screens, names):
        path = os.path.join(OUT, name)
        assert os.path.exists(path), f"{name} missing: run the script"
        assert png_size(path) == pixels(screen), f"{name}: wrong size"
    kept = {n for n in os.listdir(OUT) if n.endswith(".png")}
    assert kept == set(names), f"stray or missing PNGs: {sorted(kept ^ set(names))}"
    # The drawing itself: each screen drawn again in memory is the committed PNG, pixel for pixel
    # (rendering is deterministic), so an edit to the drawing without a rerun fails here.
    for screen, name in zip(screens, names):
        drawn = render(screen, share).convert("RGB").tobytes()
        with Image.open(os.path.join(OUT, name)) as committed:
            assert committed.convert("RGB").tobytes() == drawn, f"{name} differs from the drawing: run the script"
    tile = mark(200)
    assert tile.getpixel((0, 0)) == NIGHT
    centre = tile.getpixel((tile.width // 2, tile.height // 2))
    assert max(abs(a - b) for a, b in zip(centre, (0xFB, 0xE4, 0xDC))) <= 2, centre
    launcher_matches()
    print(f"ok: {len(screens)} screens")


def launcher_matches():
    """With the launcher in the tree, the copied geometry is still its splash's (read only here,
    never to draw): the four ring paths, the core, the scales, the alpha, the stroke, the colours."""
    if not os.path.exists(LAUNCHER_SPLASH):
        return
    xml = open(LAUNCHER_SPLASH, encoding="utf-8").read()
    assert re.findall(r'ring\d_path" android:pathData="([^"]+)"', xml) == RINGS, "the rings changed: copy them"
    r = f"{CORE_R:.2f}"
    assert f"M-{r},0a{r},{r} 0,1 0," in xml, "the core changed"
    assert f'android:scaleX="{90 / reach():.4f}"' in xml
    assert xml.count(f'android:scaleX="{RING_REST}"') == len(RINGS)
    assert f'<group android:name="core" android:scaleX="{CORE_REST}"' in xml
    assert xml.count(f'android:strokeAlpha="{RING_ALPHA}"') == len(RINGS)
    assert xml.count(f'android:strokeWidth="{STROKE}"') == len(RINGS)
    assert xml.count('android:strokeColor="#FF%02X%02X%02X"' % RING) == len(RINGS)
    assert 'android:fillColor="#FF%02X%02X%02X"' % CORE in xml


def main():
    if sys.argv[1:] == ["--selftest"]:
        return selftest()
    if sys.argv[1:]:
        sys.exit(__doc__)
    share, version, screens = load_screens()
    os.makedirs(OUT, exist_ok=True)
    for name in os.listdir(OUT):
        if name.endswith(".png"):
            os.remove(os.path.join(OUT, name))
    total = 0
    for screen in screens:
        path = os.path.join(OUT, file_name(screen))
        render(screen, share).save(path, optimize=True)
        total += os.path.getsize(path)
        print(f"{file_name(screen)}  {os.path.getsize(path)} bytes")
    head = open(HEAD, encoding="utf-8").read()
    head = head.replace(current_block(head), head_block(screens, version))
    open(HEAD, "w", encoding="utf-8").write(head)
    print(f"{len(screens)} images, {total} bytes")


if __name__ == "__main__":
    main()
