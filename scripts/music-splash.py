#!/usr/bin/env python3
"""The music app's launch splash: the Vibb mark and the wordmark "vibb music", as two vector drawables.

    python3 -I scripts/music-splash.py             # write both drawables
    python3 -I scripts/music-splash.py --selftest  # check the committed ones are what this script writes

Writes, under music/app/src/main/res/drawable/:

- splash_vibb_mark.xml - Android 12+'s `windowSplashScreenAnimatedIcon`: the Vibb mark at rest, exactly the
  launcher's Home splash at rest (launcher/app/src/main/res/drawable/splash_vibb_breathe.xml, generated by
  launcher/scripts/vibb-icon.py from palchrb/vibb pi/art - Vibb mark (c) palchrb, NOTICE.md): the four rings
  #F0A884 at stroke alpha 0.55 scaled 0.94, the cream core #FBE4DC scaled 0.9, on the 288 dp canvas with the mark
  inside the 192 dp circle (an icon without an icon background); the app's first frame draws it again, unscaled at the
  same place (ui/LaunchSplash.kt, logic/Splash.kt). Static: the hand-over's fades are the only motion.
  The ring paths are read from the launcher's drawable (hand-shaped polylines, so copied, not approximated) - the
  launcher is read, never written.
- splash_wordmark.xml - the wordmark under the rings in the app's own first frame (ui/LaunchSplash.kt; no longer the
  system splash's branding image, which Android pins to the screen's foot; still its 200 x 80 dp box, the ink centred
  in it - logic/Splash.kt's SPLASH_WORDMARK_INK_DP is the ink's height): "vibb music" in
  Nunito ExtraBold (music/app/src/main/res/font/nunito_extrabold.ttf, OFL 1.1) as filled paths - the glyph outlines
  read from the font by the small TrueType reader below (cmap 4, hmtx, loca, glyf; composite glyphs; no kerning), so
  the app draws no text at run time. "vibb" in the cream #FBE4DC, "music" in the peach #F0A884; the PWA wordmark's
  -0.025 em tracking.

Python 3, nothing else.
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLE = os.path.join(ROOT, "music", "app", "src", "main", "res", "drawable")
FONT = os.path.join(ROOT, "music", "app", "src", "main", "res", "font", "nunito_extrabold.ttf")
LAUNCHER_SPLASH = os.path.join(ROOT, "launcher", "app", "src", "main", "res", "drawable", "splash_vibb_breathe.xml")
MARK = os.path.join(DRAWABLE, "splash_vibb_mark.xml")
WORDMARK = os.path.join(DRAWABLE, "splash_wordmark.xml")

RING = "#FFF0A884"
CORE = "#FFFBE4DC"
CREAM = "#FFFBE4DC"
PEACH = "#FFF0A884"

# The wordmark's box (dp; the platform's branding size it was first drawn for) and its em (dp): "vibb music" about
# 150 dp wide.
BOX_W, BOX_H = 200, 80
EM_DP = 30.0
TRACKING_EM = -0.025

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/music-splash.py - don't edit by hand. -->
"""


# --- the mark ---------------------------------------------------------------------------------------------------


def mark_xml():
    xml = open(LAUNCHER_SPLASH, encoding="utf-8").read()
    rings = re.findall(r'ring\d_path" android:pathData="([^"]+)"', xml)
    assert len(rings) == 4, "the launcher's splash has no four rings"
    core = re.search(r'<group android:name="core"[^>]*>\s*<path android:pathData="([^"]+)"', xml).group(1)
    scale = re.search(r'android:translateX="144" android:translateY="144" android:scaleX="([\d.]+)"', xml).group(1)
    body = "".join(
        f'        <group android:scaleX="0.94" android:scaleY="0.94">\n'
        f'            <path android:pathData="{d}" android:strokeColor="{RING}" android:strokeWidth="2.6" android:strokeAlpha="0.55" />\n'
        f"        </group>\n"
        for d in rings
    )
    return HEADER + f"""<!-- The Vibb mark at rest (Vibb mark (c) palchrb, NOTICE.md): the launcher's Home splash
     (splash_vibb_breathe.xml) without its breath - the music app's launch splash icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp"
    android:height="288dp"
    android:viewportWidth="288"
    android:viewportHeight="288">
    <group android:translateX="144" android:translateY="144" android:scaleX="{scale}" android:scaleY="{scale}">
{body}        <group android:scaleX="0.9" android:scaleY="0.9">
            <path android:pathData="{core}" android:fillColor="{CORE}" />
        </group>
    </group>
</vector>
"""


# --- the wordmark: a small TrueType reader ----------------------------------------------------------------------


class Font:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        n = struct.unpack(">H", self.data[4:6])[0]
        self.tables = {}
        for i in range(n):
            tag, _, off, length = struct.unpack(">4sIII", self.data[12 + 16 * i:28 + 16 * i])
            self.tables[tag.decode()] = (off, length)
        head = self.tables["head"][0]
        self.upem = struct.unpack(">H", self.data[head + 18:head + 20])[0]
        self.long_loca = struct.unpack(">h", self.data[head + 50:head + 52])[0] == 1
        hhea = self.tables["hhea"][0]
        self.n_hmetrics = struct.unpack(">H", self.data[hhea + 34:hhea + 36])[0]
        maxp = self.tables["maxp"][0]
        self.n_glyphs = struct.unpack(">H", self.data[maxp + 4:maxp + 6])[0]
        self.cmap = self._cmap()

    def _u16(self, off):
        return struct.unpack(">H", self.data[off:off + 2])[0]

    def _cmap(self):
        base = self.tables["cmap"][0]
        for i in range(self._u16(base + 2)):
            pid, eid, off = struct.unpack(">HHI", self.data[base + 4 + 8 * i:base + 12 + 8 * i])
            sub = base + off
            if self._u16(sub) == 4 and pid in (0, 3):
                return self._format4(sub)
        raise ValueError("no cmap format 4")

    def _format4(self, sub):
        seg2 = self._u16(sub + 6)
        ends, starts = sub + 14, sub + 16 + seg2
        deltas, ranges = starts + seg2, starts + 2 * seg2
        table = {}
        for s in range(seg2 // 2):
            end, start = self._u16(ends + 2 * s), self._u16(starts + 2 * s)
            delta = struct.unpack(">h", self.data[deltas + 2 * s:deltas + 2 * s + 2])[0]
            ro = self._u16(ranges + 2 * s)
            for c in range(start, end + 1):
                if c == 0xFFFF:
                    continue
                if ro == 0:
                    g = (c + delta) & 0xFFFF
                else:
                    g = self._u16(ranges + 2 * s + ro + 2 * (c - start))
                    g = (g + delta) & 0xFFFF if g else 0
                table[c] = g
        return table

    def advance(self, glyph):
        hmtx = self.tables["hmtx"][0]
        i = min(glyph, self.n_hmetrics - 1)
        return self._u16(hmtx + 4 * i)

    def _glyph_range(self, glyph):
        loca = self.tables["loca"][0]
        if self.long_loca:
            a, b = struct.unpack(">II", self.data[loca + 4 * glyph:loca + 4 * glyph + 8])
        else:
            a, b = (2 * v for v in struct.unpack(">HH", self.data[loca + 2 * glyph:loca + 2 * glyph + 4]))
        glyf = self.tables["glyf"][0]
        return glyf + a, b - a

    def contours(self, glyph):
        """The glyph's contours, each a list of (x, y, on_curve) in font units."""
        off, length = self._glyph_range(glyph)
        if length == 0:
            return []
        n = struct.unpack(">h", self.data[off:off + 2])[0]
        if n >= 0:
            return self._simple(off, n)
        return self._composite(off)

    def _simple(self, off, n):
        p = off + 10
        ends = [self._u16(p + 2 * i) for i in range(n)]
        p += 2 * n
        p += 2 + self._u16(p)  # instructions
        count = ends[-1] + 1 if ends else 0
        flags = []
        while len(flags) < count:
            f = self.data[p]
            p += 1
            flags.append(f)
            if f & 8:
                r = self.data[p]
                p += 1
                flags.extend([f] * r)
        flags = flags[:count]

        def coords(short_bit, same_bit):
            nonlocal p
            out, v = [], 0
            for f in flags:
                if f & short_bit:
                    d = self.data[p]
                    p += 1
                    v += d if f & same_bit else -d
                elif not f & same_bit:
                    v += struct.unpack(">h", self.data[p:p + 2])[0]
                    p += 2
                out.append(v)
            return out

        xs = coords(2, 16)
        ys = coords(4, 32)
        result, start = [], 0
        for end in ends:
            result.append([(xs[i], ys[i], bool(flags[i] & 1)) for i in range(start, end + 1)])
            start = end + 1
        return result

    def _composite(self, off):
        p = off + 10
        result = []
        while True:
            flags, glyph = struct.unpack(">HH", self.data[p:p + 4])
            p += 4
            if flags & 1:
                dx, dy = struct.unpack(">hh", self.data[p:p + 4])
                p += 4
            else:
                dx, dy = struct.unpack(">bb", self.data[p:p + 2])
                p += 2
            assert flags & 2, "point-matched components aren't read"
            a, b, c, d = 1.0, 0.0, 0.0, 1.0
            f2 = lambda q: struct.unpack(">h", self.data[q:q + 2])[0] / 16384.0  # noqa: E731
            if flags & 8:
                a = d = f2(p)
                p += 2
            elif flags & 0x40:
                a, d = f2(p), f2(p + 2)
                p += 4
            elif flags & 0x80:
                a, b, c, d = f2(p), f2(p + 2), f2(p + 4), f2(p + 6)
                p += 8
            for contour in self.contours(glyph):
                result.append([(a * x + c * y + dx, b * x + d * y + dy, on) for x, y, on in contour])
            if not flags & 0x20:
                return result


def fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def contour_path(points, place):
    """One closed contour as SVG path data (quadratic B-splines with implied on-curve points)."""
    pts = [(place(x, y), on) for x, y, on in points]
    n = len(pts)
    start = next((i for i, (_, on) in enumerate(pts) if on), None)
    if start is None:  # every point off-curve: start halfway between the first two
        (x0, y0), (x1, y1) = pts[0][0], pts[1][0]
        first = ((x0 + x1) / 2, (y0 + y1) / 2)
        order = pts[1:] + pts[:1]
    else:
        first = pts[start][0]
        order = pts[start + 1:] + pts[:start]
    out = [f"M{fmt(first[0])},{fmt(first[1])}"]
    ctrl = None
    for (x, y), on in order + [(first, True)]:
        if on:
            if ctrl is None:
                out.append(f"L{fmt(x)},{fmt(y)}")
            else:
                out.append(f"Q{fmt(ctrl[0])},{fmt(ctrl[1])} {fmt(x)},{fmt(y)}")
            ctrl = None
        else:
            if ctrl is not None:
                mx, my = (ctrl[0] + x) / 2, (ctrl[1] + y) / 2
                out.append(f"Q{fmt(ctrl[0])},{fmt(ctrl[1])} {fmt(mx)},{fmt(my)}")
            ctrl = (x, y)
    assert n >= 2
    return "".join(out) + "Z"


def wordmark_xml():
    font = Font(FONT)
    scale = EM_DP / font.upem
    tracking = TRACKING_EM * font.upem
    words = [("vibb", CREAM), (" ", None), ("music", PEACH)]
    # lay out in font units, then centre the ink in the box
    pen, glyphs = 0.0, []
    for text, colour in words:
        for ch in text:
            g = font.cmap[ord(ch)]
            glyphs.append((g, pen, colour))
            pen += font.advance(g) + tracking
    ink = [(x + gx, y) for g, gx, colour in glyphs if colour for c in font.contours(g) for x, y, _ in c]
    left, right = min(x for x, _ in ink), max(x for x, _ in ink)
    bottom, top = min(y for _, y in ink), max(y for _, y in ink)
    ox = BOX_W / 2 - (left + right) / 2 * scale
    oy = BOX_H / 2 + (bottom + top) / 2 * scale  # the y axis flips: font y up, the vector's down
    paths = {CREAM: [], PEACH: []}
    for g, gx, colour in glyphs:
        if not colour:
            continue
        place = lambda x, y, gx=gx: (ox + (x + gx) * scale, oy - y * scale)  # noqa: E731
        paths[colour] += [contour_path(c, place) for c in font.contours(g)]
    width = (right - left) * scale
    height = (top - bottom) * scale
    assert width < BOX_W - 16 and height < BOX_H - 16, (width, height)
    body = "".join(
        f'    <path android:pathData="{"".join(paths[c])}" android:fillColor="{c}" />\n' for c in (CREAM, PEACH)
    )
    return HEADER + f"""<!-- "vibb music" in Nunito ExtraBold (OFL 1.1, assets/licenses/OFL.txt) as paths: the wordmark under the
     rings in the app's launch splash ({fmt(width)} x {fmt(height)} dp of ink centred in {BOX_W} x {BOX_H} dp). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{BOX_W}dp"
    android:height="{BOX_H}dp"
    android:viewportWidth="{BOX_W}"
    android:viewportHeight="{BOX_H}">
{body}</vector>
"""


def main():
    outputs = {MARK: mark_xml(), WORDMARK: wordmark_xml()}
    if sys.argv[1:] == ["--selftest"]:
        for path, text in outputs.items():
            assert open(path, encoding="utf-8").read() == text, f"{os.path.basename(path)} differs: run the script"
        print("ok: the splash drawables are the script's")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    for path, text in outputs.items():
        open(path, "w", encoding="utf-8").write(text)
        print(f"{os.path.relpath(path, ROOT)}  {len(text)} bytes")


if __name__ == "__main__":
    main()
