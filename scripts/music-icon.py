#!/usr/bin/env python3
"""The music app's launcher icon and notification small icon: three of the Vibb mark's rings with a play button.

    python3 -I scripts/music-icon.py             # write both drawables
    python3 -I scripts/music-icon.py --selftest  # check the committed ones are what this script writes

The user's own drawing `vibb-music-q7` (1024 px, 2026-11-15) rebuilt as vectors, so it is the same picture at every
size: night rings on the Vibb peach, the Vibb mark's outer three rings (Vibb mark (c) palchrb, NOTICE.md) and a play
triangle with round corners, nudged right, where the mark's inner ring and dot are. Its geometry, measured on the
1024 px PNG: the drawing is a 60-unit canvas (the PWA mark's viewBox -30..30), the rings at 0.92 of the mark with a
stroke of 3.6 mark units, the play triangle as below. The ring paths are read from the launcher's adaptive icon
(launcher/app/src/main/res/drawable/ic_launcher_foreground.xml, from palchrb/vibb pi/art by
launcher/scripts/vibb-icon.py) - hand-shaped polylines, so copied, not approximated; the launcher is read, never
written.

Writes, under music/app/src/main/res/drawable/:

- ic_launcher_foreground.xml - the adaptive icon's foreground and its monochrome (themed) layer
  (mipmap-anydpi-v26/ic_launcher.xml; the background is @color/vibb_peach): the drawing's 60-unit canvas on the
  72 dp visible area of the 108 dp layer (1.2 dp a unit), so the outer ring's outer edge stays inside the 66 dp safe
  zone (the self-test checks it).
- ic_stat_vibb_music.xml - the notification small icon (the media notification and the new-episodes one): the same
  shape in white on transparent (Android draws a small icon from its alpha alone), the outer ring's outer edge in the
  22 dp live area of the 24 dp canvas.

Python 3, nothing else.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLE = os.path.join(ROOT, "music", "app", "src", "main", "res", "drawable")
LAUNCHER_ICON = os.path.join(ROOT, "launcher", "app", "src", "main", "res", "drawable", "ic_launcher_foreground.xml")
FOREGROUND = os.path.join(DRAWABLE, "ic_launcher_foreground.xml")
SMALL = os.path.join(DRAWABLE, "ic_stat_vibb_music.xml")

NIGHT = "#FF0C0C14"
WHITE = "#FFFFFFFF"

# The drawing: a 60-unit canvas centred on 0 (the 1024 px PNG is 1024/60 px a unit).
CANVAS = 60.0
PNG_PX = 1024.0
RINGS = 3  # the mark's outer three (of four; the inner one and the dot gave way to the play button)
RING_SCALE = 0.92
RING_STROKE = 3.6  # mark units, before RING_SCALE
# The play triangle on the 1024 px PNG (fitted to its anti-aliased edges): the sharp triangle's left side, its half
# height (centred on the canvas), its tip, and the corners' radius, all in px.
TRI_LEFT_PX = 432.52
TRI_HALF_PX = 123.12
TRI_TIP_PX = 659.10
TRI_CORNER_PX = 18.36

# Adaptive icon: 108 dp layer, 72 dp visible, 66 dp safe zone. Small icon: 24 dp, 22 dp live.
LAYER_DP, VISIBLE_DP, SAFE_DP = 108, 72, 66
SMALL_DP, SMALL_LIVE_DP = 24, 22

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/music-icon.py - don't edit by hand. The Vibb mark's rings (c) palchrb (NOTICE.md), from
     the launcher's ic_launcher_foreground.xml; the drawing is the user's vibb-music-q7. -->
"""


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def ring_paths():
    xml = open(LAUNCHER_ICON, encoding="utf-8").read()
    paths = re.findall(r'android:pathData="(M[^"]+)" android:strokeColor', xml)
    assert len(paths) == 4, "the launcher's icon has no four rings"
    return paths[:RINGS]


def reach(paths):
    """The outer ring's outer edge from the centre, in canvas units."""
    r = max(math.hypot(float(x), float(y)) for d in paths for x, y in re.findall(r"(-?[\d.]+) (-?[\d.]+)", d))
    return (r + RING_STROKE / 2) * RING_SCALE


def px(v):
    return (v - PNG_PX / 2) * CANVAS / PNG_PX


def play_path():
    """The rounded play triangle in canvas units: straight sides, each corner a tangent arc."""
    left, half, tip = px(TRI_LEFT_PX), TRI_HALF_PX * CANVAS / PNG_PX, px(TRI_TIP_PX)
    r = TRI_CORNER_PX * CANVAS / PNG_PX
    corners = [(left, -half), (tip, 0.0), (left, half)]  # clockwise on screen (y down)
    ins, outs = [], []
    for i, p in enumerate(corners):
        a, b = corners[i - 1], corners[(i + 1) % 3]
        u = [(a[k] - p[k]) / math.dist(a, p) for k in (0, 1)]
        v = [(b[k] - p[k]) / math.dist(b, p) for k in (0, 1)]
        t = r / math.tan(math.acos(u[0] * v[0] + u[1] * v[1]) / 2)
        ins.append((p[0] + u[0] * t, p[1] + u[1] * t))
        outs.append((p[0] + v[0] * t, p[1] + v[1] * t))
    d = f"M{fmt(outs[0][0])},{fmt(outs[0][1])}"
    for i in (1, 2, 0):
        d += f"L{fmt(ins[i][0])},{fmt(ins[i][1])}A{fmt(r)},{fmt(r)} 0,0 1 {fmt(outs[i][0])},{fmt(outs[i][1])}"
    return d + "Z"


def vector(side, scale, colour, paths, comment):
    rings = "".join(
        f'            <path android:pathData="{d}" android:strokeColor="{colour}" android:strokeWidth="{RING_STROKE}" />\n'
        for d in paths
    )
    c = side / 2
    return HEADER + f"""<!-- {comment}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{side}dp"
    android:height="{side}dp"
    android:viewportWidth="{side}"
    android:viewportHeight="{side}">
    <group android:translateX="{fmt(c)}" android:translateY="{fmt(c)}" android:scaleX="{fmt(scale)}" android:scaleY="{fmt(scale)}">
        <group android:scaleX="{RING_SCALE}" android:scaleY="{RING_SCALE}">
{rings}        </group>
        <path android:pathData="{play_path()}" android:fillColor="{colour}" />
    </group>
</vector>
"""


def outputs():
    paths = ring_paths()
    edge = reach(paths)
    fg_scale = VISIBLE_DP / CANVAS
    assert edge * fg_scale < SAFE_DP / 2, f"the outer ring leaves the safe zone: {edge * fg_scale:.2f} dp"
    small_scale = math.floor(SMALL_LIVE_DP / 2 / edge * 1000) / 1000
    return {
        FOREGROUND: vector(
            LAYER_DP, fg_scale, NIGHT, paths,
            f"The adaptive icon's foreground and monochrome layer, on @color/vibb_peach: the drawing's\n"
            f"     {fmt(CANVAS)}-unit canvas on the {VISIBLE_DP} dp visible area; the outer ring's outer edge "
            f"{fmt(edge * fg_scale)} dp from the centre\n     (the safe zone: {SAFE_DP // 2} dp)",
        ),
        SMALL: vector(
            SMALL_DP, small_scale, WHITE, paths,
            "The notification small icon: the launcher icon's shape in white on transparent, the outer ring's\n"
            f"     outer edge {fmt(edge * small_scale)} dp from the centre (the {SMALL_LIVE_DP} dp live area)",
        ),
    }


def main():
    out = outputs()
    if sys.argv[1:] == ["--selftest"]:
        for path, text in out.items():
            assert open(path, encoding="utf-8").read() == text, f"{os.path.basename(path)} differs: run the script"
        print("ok: the icon drawables are the script's")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    for path, text in out.items():
        open(path, "w", encoding="utf-8").write(text)
        print(f"{os.path.relpath(path, ROOT)}  {len(text)} bytes")


if __name__ == "__main__":
    main()
