#!/usr/bin/env python3
"""The music app's launcher icon and notification small icon: three of the Vibb mark's rings with a play button.

    python3 -I scripts/music-icon.py             # write both drawables
    python3 -I scripts/music-icon.py --selftest  # check the committed ones are what this script writes

The user's own drawing `vibb-music-p82` (2026-11-17: "Kjør på p82% logoen"; q7's rings with the play sign shrunk to
82 % around its own centroid, for air between the play sign and the inner ring - e2m before it) rebuilt as vectors, so
it is the same picture at every size: night rings on the Vibb peach, the
Vibb mark's outer three rings (Vibb mark (c) palchrb, NOTICE.md) and a play triangle with round corners, nudged right,
where the mark's inner ring and dot are. Its geometry, from the drawing's vector: a 100-unit full-bleed canvas (viewBox 0
0 100 100), the three rings at the mark's own spacing (one scale and stroke for all, so every ring is drawn 5.52 units
wide), the play sign q7's at 82 % about its centroid (x -0.53), its round-join stroke scaled with it. The ring
paths are read from the launcher's adaptive icon (launcher/app/src/main/res/drawable/ic_launcher_foreground.xml, from
palchrb/vibb pi/art by launcher/scripts/vibb-icon.py) - hand-shaped polylines, so copied, not approximated; the
launcher is read, never written.

Writes, under music/app/src/main/res/drawable/:

- ic_launcher_foreground.xml - the adaptive icon's foreground and its monochrome (themed) layer
  (mipmap-anydpi-v26/ic_launcher.xml; the background is @color/vibb_peach): the drawing's 100-unit canvas on the
  72 dp visible area of the 108 dp layer (0.72 dp a unit), so the outer ring's outer edge stays inside the 66 dp safe
  zone (the self-test checks it).
- ic_stat_vibb_music.xml - the notification small icon (the media notification and the new-episodes one): the same
  shape in white on transparent (Android draws a small icon from its alpha alone), the outer ring's outer edge in the
  22 dp live area of the 24 dp canvas.

Python 3, nothing else.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLE = os.path.join(ROOT, "music", "app", "src", "main", "res", "drawable")
LAUNCHER_ICON = os.path.join(ROOT, "launcher", "app", "src", "main", "res", "drawable", "ic_launcher_foreground.xml")
FOREGROUND = os.path.join(DRAWABLE, "ic_launcher_foreground.xml")
SMALL = os.path.join(DRAWABLE, "ic_stat_vibb_music.xml")

NIGHT = "#FF0C0C14"
WHITE = "#FFFFFFFF"

# The drawing: a 100-unit canvas centred on 0 (the SVG's viewBox 0 0 100 100, centre 50).
CANVAS = 100.0
RINGS = 3  # the mark's outer three (of four; the inner one and the dot gave way to the play button)
# Each ring's scale (of the launcher's path) and stroke (in path units, before the scale): the same for all three since
# P82, so the drawn stroke is 5.52 canvas units and the spacing the Vibb mark's own.
RING_SCALES = (1.5333, 1.5333, 1.5333)
RING_STROKES = (3.600, 3.600, 3.600)
# The play triangle, canvas units from the centre: a sharp triangle drawn with a round-join stroke, which is what
# rounds its corners.
TRI = ((-5.962, -8.856), (10.333, 0.0), (-5.962, 8.856))
TRI_STROKE = 3.542

# Adaptive icon: 108 dp layer, 72 dp visible, 66 dp safe zone. Small icon: 24 dp, 22 dp live.
LAYER_DP, VISIBLE_DP, SAFE_DP = 108, 72, 66
SMALL_DP, SMALL_LIVE_DP = 24, 22

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/music-icon.py - don't edit by hand. The Vibb mark's rings (c) palchrb (NOTICE.md), from
     the launcher's ic_launcher_foreground.xml; the drawing is the user's vibb-music-e2m. -->
"""


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def ring_paths():
    xml = open(LAUNCHER_ICON, encoding="utf-8").read()
    paths = re.findall(r'android:pathData="(M[^"]+)" android:strokeColor', xml)
    assert len(paths) == 4, "the launcher's icon has no four rings"
    return paths[:RINGS]


def radii(d):
    r = [math.hypot(float(x), float(y)) for x, y in re.findall(r"(-?[\d.]+) (-?[\d.]+)", d)]
    return min(r), max(r)


def reach(paths):
    """The outer ring's outer edge from the centre, in canvas units."""
    return max((radii(d)[1] + w / 2) * s for d, s, w in zip(paths, RING_SCALES, RING_STROKES))


def spacing(paths):
    """The distance between the rings' mean radii, outer to inner, in canvas units (even: the drawing's point)."""
    mid = [sum(radii(d)) / 2 * s for d, s in zip(paths, RING_SCALES)]
    return [a - b for a, b in zip(mid, mid[1:])]


def play_path():
    """The play triangle in canvas units; the stroke (TRI_STROKE, round joins) rounds its corners."""
    (a, b), (c, d), (e, f) = TRI
    return f"M{fmt(a)},{fmt(b)}L{fmt(c)},{fmt(d)}L{fmt(e)},{fmt(f)}Z"


def vector(side, scale, colour, paths, comment):
    rings = "".join(
        f'        <group android:scaleX="{s:g}" android:scaleY="{s:g}">\n'
        f'            <path android:pathData="{d}" android:strokeColor="{colour}" android:strokeWidth="{fmt(w)}" />\n'
        "        </group>\n"
        for d, s, w in zip(paths, RING_SCALES, RING_STROKES)
    )
    c = side / 2
    return HEADER + f"""<!-- {comment}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{side}dp"
    android:height="{side}dp"
    android:viewportWidth="{side}"
    android:viewportHeight="{side}">
    <group android:translateX="{fmt(c)}" android:translateY="{fmt(c)}" android:scaleX="{fmt(scale)}" android:scaleY="{fmt(scale)}">
{rings}        <path android:pathData="{play_path()}" android:fillColor="{colour}" android:strokeColor="{colour}" android:strokeWidth="{fmt(TRI_STROKE)}" android:strokeLineJoin="round" />
    </group>
</vector>
"""


def outputs():
    paths = ring_paths()
    edge = reach(paths)
    fg_scale = VISIBLE_DP / CANVAS
    gaps = spacing(paths)
    assert max(gaps) - min(gaps) < 0.25, f"the rings are not evenly spaced: {gaps}"
    assert edge * fg_scale < SAFE_DP / 2, f"the outer ring leaves the safe zone: {edge * fg_scale:.2f} dp"
    small_scale = math.floor(SMALL_LIVE_DP / 2 / edge * 1000) / 1000
    return {
        FOREGROUND: vector(
            LAYER_DP, fg_scale, NIGHT, paths,
            f"The adaptive icon's foreground and monochrome layer, on @color/vibb_peach: the drawing's\n"
            f"     {fmt(CANVAS)}-unit canvas on the {VISIBLE_DP} dp visible area; the outer ring's outer edge "
            f"{fmt(edge * fg_scale)} dp from the centre\n     (the safe zone: {SAFE_DP // 2} dp)",
        ),
        SMALL: vector(
            SMALL_DP, small_scale, WHITE, paths,
            "The notification small icon: the launcher icon's shape in white on transparent, the outer ring's\n"
            f"     outer edge {fmt(edge * small_scale)} dp from the centre (the {SMALL_LIVE_DP} dp live area)",
        ),
    }


def main():
    out = outputs()
    if sys.argv[1:] == ["--selftest"]:
        for path, text in out.items():
            assert open(path, encoding="utf-8").read() == text, f"{os.path.basename(path)} differs: run the script"
        print("ok: the icon drawables are the script's")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    for path, text in out.items():
        open(path, "w", encoding="utf-8").write(text)
        print(f"{os.path.relpath(path, ROOT)}  {len(text)} bytes")


if __name__ == "__main__":
    main()
