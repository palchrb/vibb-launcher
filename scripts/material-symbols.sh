while read -r name sha; do
    curl -sfL -o "$work/$name.svg" "$BASE/symbols/web/$name/materialsymbolsrounded/${name}_fill1_24px.svg"
    echo "$sha  $work/$name.svg" | sha256sum -c --quiet -
done < "$work/hashes"
curl -sfL -o "$work/LICENSE" "$BASE/LICENSE"
echo "$LICENSE_SHA256  $work/LICENSE" | sha256sum -c --quiet -

python3 - "$work" "$COMMIT" <<'PY'
import json, os, re, shutil, sys

work, commit = sys.argv[1], sys.argv[2]
table = json.load(open("server/testdata/app_icons.json"))
icons, colors = table["icons"], table["colors"]
source = f"google/material-design-icons at {commit[:12]}"

os.makedirs("server/static/app-icons", exist_ok=True)
os.makedirs("launcher/app/src/main/assets/licenses", exist_ok=True)

for key, name in icons.items():
    svg = open(os.path.join(work, f"{name}.svg")).read()
    if 'viewBox="0 -960 960 960"' not in svg:
        sys.exit(f"{name}: unexpected viewBox")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        sys.exit(f"{name}: expected one path, found {len(paths)}")
    d = paths[0]
    note = (f'Converted from Material Symbols "{name}" (Rounded, filled, 24 px; {source}), '
            "Apache License 2.0")
    with open(f"launcher/app/src/main/res/drawable/app_glyph_{key}.xml", "w") as out:
        out.write('<?xml version="1.0" encoding="utf-8"?>\n'
                  f"<!-- {note} (assets/licenses/Apache-2.0.txt).\n"
                  "     Changed: SVG to an Android vector, white fill. Generated by scripts/material-symbols.sh. -->\n"
                  '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                  '    android:width="24dp"\n    android:height="24dp"\n'
                  '    android:viewportWidth="960"\n    android:viewportHeight="960">\n'
                  '    <group android:translateY="960">\n'
                  f'        <path\n            android:fillColor="#FFFFFFFF"\n            android:pathData="{d}" />\n'
                  "    </group>\n</vector>\n")
    with open(f"server/static/app-icons/{key}.svg", "w") as out:
        out.write(f"<!-- {note} (LICENSE.txt). Changed: white fill. Generated by scripts/material-symbols.sh. -->\n"
                  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" width="24" height="24">'
                  f'<path fill="#fff" d="{d}"/></svg>\n')

shutil.copy(os.path.join(work, "LICENSE"), "launcher/app/src/main/assets/licenses/Apache-2.0.txt")
shutil.copy(os.path.join(work, "LICENSE"), "server/static/app-icons/LICENSE.txt")
shutil.copy("server/testdata/app_icons.json", "launcher/app/src/test/resources/app_icons.json")

def argb(hex_rgb):
    return "0xFF" + hex_rgb.lstrip("#").upper()

with open("launcher/app/src/main/java/com/kidslauncher/mdm/apps/AppGlyphs.kt", "w") as out:
    out.write("// Generated by scripts/material-symbols.sh from server/testdata/app_icons.json - don't edit.\n"
              "package com.kidslauncher.mdm.apps\n\n"
              "import com.kidslauncher.mdm.R\n\n"
              "/** A tile colour: the seed the parent picked and [tile] = `tileColor(seed)` (ARGB). */\n"
              "data class AppColor(val seed: Int, val tile: Int)\n\n"
              "/**\n * The parent's icon and colour choices for an app (design 14): Material Symbols Rounded, filled\n"
              " * (Apache-2.0, `res/drawable/app_glyph_*.xml`), and the tile colours. `AppGlyphsTest` checks them\n"
              " * against `app_icons.json`.\n */\n"
              "object AppGlyphs {\n"
              "    /** Icon key -> its white glyph. */\n"
              "    val ICONS: Map<String, Int> = linkedMapOf(\n")
    for key in icons:
        out.write(f'        "{key}" to R.drawable.app_glyph_{key},\n')
    out.write("    )\n\n    /** Icon key -> the Material Symbols name. */\n"
              "    val SYMBOLS: Map<String, String> = linkedMapOf(\n")
    for key, name in icons.items():
        out.write(f'        "{key}" to "{name}",\n')
    out.write("    )\n\n    /** Colour key -> seed and tile. */\n"
              "    val COLORS: Map<String, AppColor> = linkedMapOf(\n")
    for key, c in colors.items():
        out.write(f'        "{key}" to AppColor({argb(c["seed"])}.toInt(), {argb(c["tile"])}.toInt()),\n')
    out.write("    )\n}\n")

with open("server/src/app_icons.rs", "w") as out:
    out.write("//! Generated by scripts/material-symbols.sh from testdata/app_icons.json - don't edit. The\n"
              "//! parent's icon and colour choices for an app on the kid's launcher (design 14); the glyphs are\n"
              "//! `static/app-icons/<key>.svg` (Material Symbols Rounded, filled, Apache-2.0).\n\n"
              "/// Icon key -> Material Symbols name.\n"
              "pub const ICONS: &[(&str, &str)] = &[\n")
    for key, name in icons.items():
        out.write(f'    ("{key}", "{name}"),\n')
    out.write("];\n\n/// Colour key -> (seed, tile): the tile is the launcher's `tileColor(seed)`.\n"
              "pub const COLORS: &[(&str, &str, &str)] = &[\n")
    for key, c in colors.items():
        out.write(f'    ("{key}", "{c["seed"]}", "{c["tile"]}"),\n')
    out.write("];\n")
PY
echo "Done: $(python3 -c 'import json; print(len(json.load(open("server/testdata/app_icons.json"))["icons"]))') icons."
