#!/bin/sh
# The parent's app icons (design docs/design/14-app-display.md): Material Symbols Rounded, filled,
# 24 px, from google/material-design-icons pinned to one commit and checked by SHA-256 (Apache
# License 2.0, compatible with GPL-3.0). Run from the repository root after changing
# server/testdata/app_icons.json (a new icon also needs its hash below). Needs curl, sha256sum and
# python3. Writes:
#   launcher/app/src/main/res/drawable/app_glyph_<key>.xml   (Android vectors, white)
#   launcher/app/src/main/java/com/kidslauncher/mdm/apps/AppGlyphs.kt   (the launcher's table)
#   launcher/app/src/main/assets/licenses/Apache-2.0.txt
#   launcher/app/src/test/resources/app_icons.json   (copy of the server's)
#   server/static/app-icons/<key>.svg and LICENSE.txt   (the PWA's preview)
#   server/src/app_icons.rs   (the server's table)
# Every converted file says what it was converted from (Apache-2.0 §4(b)).
set -eu
COMMIT=737e3324305806514d7909874fa1818ae1808232
BASE="https://raw.githubusercontent.com/google/material-design-icons/$COMMIT"
LICENSE_SHA256=58d1e17ffe5109a7ae296caafcadfdbe6a7d176f0bc4ab01e12a689b0499d8bd

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# name sha256 (symbols/web/<name>/materialsymbolsrounded/<name>_fill1_24px.svg)
cat > "$work/hashes" <<'HASHES'
